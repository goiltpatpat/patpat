#!/usr/bin/env python3
"""Reject AI-agent attribution in commit messages and pull request bodies (AGENTS.md repository rule)."""

from __future__ import annotations

import argparse
import os
import re
import subprocess
import sys
import tempfile
from pathlib import Path

AGENT_NAMES = re.compile(
    r"\b(claude|anthropic|openai|chatgpt|codex|copilot|cursor ?agent|gemini|grok|devin|aider|windsurf)\b", re.IGNORECASE
)
AGENT_EMAILS = {"noreply@anthropic.com", "cursoragent@cursor.com"}
CO_AUTHOR = re.compile(r"(?im)^\s*co-authored-by:\s*(?P<name>[^<\n]*?)\s*(?:<(?P<email>[^>\n]*)>)?\s*$")
GENERATED = re.compile(r"(?im)^\s*(?:🤖\s*)?generated (?:with|by)\b(?P<rest>.*)$")


def find_attribution(text: str) -> list[str]:
    """Return agent attribution lines; a human co-author or a tool-generated note passes."""
    hits = []
    for match in CO_AUTHOR.finditer(text):
        if AGENT_NAMES.search(match["name"]) or (match["email"] or "").strip().lower() in AGENT_EMAILS:
            hits.append(f"agent Co-Authored-By trailer: {match.group(0).strip()}")
    for match in GENERATED.finditer(text):
        if AGENT_NAMES.search(match["rest"]) or "🤖" in match.group(0):
            hits.append(f"'Generated with' footer: {match.group(0).strip()}")
    return hits


def commit_messages(root: Path, revision_range: str) -> list[tuple[str, str]]:
    completed = subprocess.run(
        ["git", "log", "--format=%H%x00%B%x01", revision_range],
        cwd=root, check=False, capture_output=True, text=True, encoding="utf-8", errors="replace",
    )
    if completed.returncode != 0:
        detail = completed.stderr.strip().splitlines()[-1:] or ["git log failed"]
        raise SystemExit(f"cannot read commits in {revision_range!r}: {detail[0]} (after a force-push, rerun with --range HEAD^!)")
    output = completed.stdout
    entries = []
    for record in output.split("\x01"):
        if "\x00" in record:
            sha, body = record.split("\x00", 1)
            entries.append((sha.strip()[:12], body))
    return entries


def check(root: Path, revision_range: str, body_env: str | None) -> list[str]:
    problems = []
    for sha, body in commit_messages(root, revision_range):
        problems.extend(f"commit {sha}: {hit}" for hit in find_attribution(body))
    if body_env:
        problems.extend(f"pull request body: {hit}" for hit in find_attribution(os.environ.get(body_env, "")))
    return problems


def self_test() -> int:
    with tempfile.TemporaryDirectory() as temp:
        root = Path(temp)

        def git(*args: str) -> None:
            subprocess.run(["git", *args], cwd=root, check=True, capture_output=True)

        git("init", "-q")
        git("config", "user.email", "self-test@example.invalid")
        git("config", "user.name", "self-test")
        git("commit", "-q", "--allow-empty", "-m", "feat: clean\n\nGenerated by scripts/stage_plugin.py\nCo-Authored-By: Pat Human <pat@openai.com>")
        clean = check(root, "HEAD", None)
        git("commit", "-q", "--allow-empty", "-m", "fix: x\n\nCo-Authored-By: Claude Opus 5.5 <noreply@anthropic.com>")
        trailer = check(root, "HEAD^!", None)
        os.environ["SELF_TEST_PR_BODY"] = "Summary\n\n🤖 Generated with [Claude Code](https://claude.com/claude-code)"
        footer = check(root, "HEAD~1^!", "SELF_TEST_PR_BODY")
        os.environ.pop("SELF_TEST_PR_BODY")
    results = {
        "human co-author passes": clean == [],
        "trailer without email fails": len(find_attribution("x\n\nCo-Authored-By: Claude\n")) == 1,
        "agent trailer fails":len(trailer) == 1 and "Co-Authored-By" in trailer[0],
        "generated footer in PR body fails": len(footer) == 1 and footer[0].startswith("pull request body"),
    }
    for name, ok in results.items():
        if not ok:
            print(f"FAIL {name}", file=sys.stderr)
    if not all(results.values()):
        return 1
    print(f"check_attribution self-test ok: {len(results)} cases")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path.cwd())
    parser.add_argument("--range", default="HEAD^!", help="git revision range to inspect (default: the HEAD commit)")
    parser.add_argument("--body-env", help="environment variable holding a pull request body to inspect")
    parser.add_argument("--self-test", action="store_true")
    args = parser.parse_args()
    if args.self_test:
        return self_test()
    problems = check(args.root, args.range, args.body_env)
    if problems:
        for problem in problems:
            print(problem, file=sys.stderr)
        print("Remove agent attribution: AGENTS.md 'Repository rules' forbids it in commits and PR bodies.", file=sys.stderr)
        return 1
    print(f"attribution ok: {args.range}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
